"""Round 8: does any learned model predict the size of a combination's effect better than additivity?

Rounds 1 to 7 scored predictions by Δ-correlation, which ignores scale: a predicted change
with the right shape and the wrong size scores perfectly. Round 7 found the additive
reference (the sum of the two singles' measured effects) at 0.961 on that metric, leaving
almost no room above it. Round 8 scores the size of the change as well, on the same
twenty held-out pairs, from existing checkpoints only. Nothing is trained.

PROTOCOL (fixed in writing before any number below the disclosure was computed)
================================================================================

Disclosure: what was known when this was written. (1) The additive reference's value on
the primary endpoint is Round 4's relative interaction, median 0.272, as the ledger's
proposal for this round stated. (2) The composition ablation, scored on 2026-11-06,
reported the primary endpoint descriptively for both primary learned arms (same
checkpoints, same predictions): mean e_p 1.053 for the conditioned NB-VAE and 1.261 for
the transport flow, with neither below the additive reference on any pair. The primary
verdict is therefore not blind. The endpoint and the rule below were written in the
ledger before those numbers existed and are unchanged; this protocol only fills gaps the
ledger left open, using the ledger's wording wherever it is specific. (3) While the
scoring code was smoke-tested, before this protocol was committed, two numbers were
printed: the conditioned NB-VAE's seed-0 mean e_p (1.039, consistent with (2)) and the
pair-agnostic average reference's mean e_p (0.803), an exploratory arm that carries no
verdict. No other number below was seen: not the condition-blind NB-VAE or the Gaussian
flow, the scale secondary, the all-gene error, or the noise floor on the e scale. The
smoke test also confirmed that λ_p computed here reproduces Round 4's scale on all 20
pairs to 3e-7, a check on the truth only.

Pairs, genes, space. The 20 held-out combinations of the combo split that the standing
benchmark scores (at least 20 held-out cells). For pair p = A+B, the genes T_p are its
top-20 DE genes by Wilcoxon |z|, the set Δ-correlation uses; space log1p-CP10K. Control
mean over all control cells. Δ_p = held-out pair mean − control mean (the truth);
Δ̂_p = predicted mean − control mean; Δ_A, Δ_B = each single's measured change from its
training cells; a_p = Δ_A + Δ_B (the additive prediction); I_p = Δ_p − a_p.

Primary endpoint (as in the ledger). e_p = ‖Δ̂_p − Δ_p‖ / ‖Δ_p‖ on T_p, lower better. For
the additive reference e_p = ‖I_p‖ / ‖Δ_p‖, Round 4's rel_GI.

Primary arms.
    additive         the additive reference                 norman_additive (deterministic)
    vae_cond         conditioned NB-VAE, q(z|x,c)            norman_vae_cond_s{0,1,2}
    flow_transport   transport flow, control base            norman_sweep_control_s{0,1,2}
Flows are decoded by the canonical count decoder (md5 52a44337; every flow run's own
decoder file is byte-identical to it).

Predictions. Generated by 19 exactly as 06 (flows) and 09 (NB-VAE) generate them: 200
cells per pair, generation seed 0, 100 Euler steps and guidance 1 for flows. 19 stops
unless its per-pair Δ-correlation reproduces the run's stored report to 1e-9.

Aggregation order. Per pair and seed compute e_p; average over the three seeds per pair
(arithmetic); the arm's score is the arithmetic mean over pairs.

Contrasts. One family, per-pair paired differences of seed-averaged e_p:
    vae_cond − additive        flow_transport − additive
Joint paired bootstrap over pairs, 10,000 resamples, generator seed 0, one resample
shared by the family and every secondary; max-t simultaneous 95% intervals
(ssllab.eval.bootstrap, the procedure of 12).

Decision rule. A learned model improves on additivity in magnitude only if its
simultaneous interval lies wholly below 0 (the ledger's rule). Its complement, fixed here:
wholly above 0 means additivity predicts the size and shape of the change better than
that model; an interval containing 0 is inconclusive. No outcome changes a reference:
additivity stays the reference on Δ-correlation and the conditioned NB-VAE the strongest
learned baseline and the only population reference.

Near zero and missing values. e_p is NaN when ‖Δ_p‖ < 1e-12; no floor on the numerator
(e_p is not logged). A pair enters the primary family only if e_p is finite for every
primary arm and every seed; excluded pairs are listed. A verdict needs at least 18 of the
20 pairs, otherwise the primary is reported as not evaluable.

Reported beside the primary, no verdict. Per-pair e_p for every arm; the fraction of
pairs where a learned arm's e_p is below additivity's; the geometric-mean error ratio to
additivity (exp of the mean seed-averaged log r_p, the composition ablation's primary,
for cross-reading only).

Secondaries, percentile intervals on the shared resample, no verdicts.
    1. Interaction recovery: Pearson correlation on T_p between Δ̂_p − a_p and I_p
       (undefined for the additive reference). Diagnostic beside it: the same with the
       model's own predicted singles (generated after the pairs, generator seeded 1).
    2. Scale against Round 4's λ: λ_p = ⟨Δ_p, a_p⟩/‖a_p‖², s_p = ⟨Δ̂_p, a_p⟩/‖a_p‖²
       (additive: s_p = 1). Reported: mean |s_p − λ_p| (per seed, then seed mean, then
       pair mean), its difference from additivity's |1 − λ_p|, and the Pearson
       correlation across pairs between seed-averaged s_p and λ_p.
    3. e_p over all 5,000 measured genes, and its difference from additivity's.
    4. Δ-correlation, recomputed, as the link to Rounds 1 to 7.

Noise floor. Per pair, the held-out cells are split at random into halves (seed 0);
f_p = ½‖mean₁ − mean₂‖ / ‖Δ_p‖ on T_p, and the same over all genes. Reported beside every
arm as the error a perfect predictor would show.

Exploratory arms, no verdict, each against additivity with percentile intervals.
    vae_blind        condition-blind NB-VAE, q(z|x), Round 6     norman_vae_blind_s{0,1,2}
    flow_gaussian    flow from a Gaussian base                  norman_sweep_gaussian_s{0,1,2}
    average          Round 7's pair-agnostic average training profile   norman_additive

Stratification, descriptive. The 10 pairs with the largest rel_GI reported separately:
each arm's e_p and its difference from additivity, percentile intervals.

Out of this round, listed as future work: a Systema-style reference (change measured
against the average perturbed cell; it defines a different additive reference),
cross-validation over all 131 pairs and held-out singles (both need retraining).

Usage
-----
    # after 19 has scored every arm (run_round8_score_pod.sh does both on the pod)
    python examples/perturbation_response/21_score_round8.py --out output/round8_compare.json
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path

import numpy as np

_SRC = Path(__file__).resolve().parents[2] / "src"
if str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

from ssllab.eval.bootstrap import maxt_family, percentile_interval, resample_indices

logging.basicConfig(level=logging.INFO, format="%(message)s")
logger = logging.getLogger(__name__)

PRIMARY_ARMS = {
    "additive": ("norman_additive", "additive"),
    "vae_cond": ("norman_vae_cond_s{s}", "vae"),
    "flow_transport": ("norman_sweep_control_s{s}", "flow"),
}
EXPLORATORY_ARMS = {
    "vae_blind": ("norman_vae_blind_s{s}", "vae"),
    "flow_gaussian": ("norman_sweep_gaussian_s{s}", "flow"),
    "average": ("norman_additive", "average"),
}
REFERENCE = "additive"
CONTRASTS = [("vae_cond", REFERENCE), ("flow_transport", REFERENCE)]
PRIMARY = "rel_err"
PER_SEED = ["rel_err", "log_r", "rel_err_all", "interaction_r", "internal_r", "delta_r", "scale", "scale_abs_err"]
MIN_PAIRS = 18
N_PAIRS_EXPECTED = 20
N_STRONG = 10


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Round 8: magnitude-aware endpoint against the additive reference.")
    p.add_argument("--output-root", default="output")
    p.add_argument("--seeds", default="0,1,2")
    p.add_argument("--n-boot", type=int, default=10000)
    p.add_argument("--alpha", type=float, default=0.05)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", default=None)
    return p.parse_args()


def load_arm(pattern: str, kind: str, seeds: list[int], root: str) -> tuple[dict, dict]:
    """Seed-average every metric per pair: ({metric: {pair: value}}, {pair: per-pair constants}).

    A pair keeps a metric only if every seed gives a finite value. A training-free arm
    (no ``{s}`` in its pattern) has a single report.
    """
    runs = [pattern.format(s=s) for s in seeds] if "{s}" in pattern else [pattern]
    acc: dict[str, dict[str, list[float]]] = {}
    const: dict[str, dict] = {}
    for run in runs:
        path = Path(root) / run / "reports" / f"interaction_{kind}.json"
        if not path.exists():
            raise SystemExit(f"missing {path}; run 19_score_interaction.py first")
        for pair, d in json.loads(path.read_text())["per_pert"].items():
            d = dict(d)
            d["scale_abs_err"] = abs(d["scale"] - d["lam"])
            for m in PER_SEED:
                acc.setdefault(m, {}).setdefault(pair, []).append(float(d[m]))
            const[pair] = {k: d[k] for k in ("rel_gi", "lam", "floor_e", "floor_e_all")}
    out = {m: {p: float(np.mean(v)) for p, v in per.items() if len(v) == len(runs) and all(np.isfinite(v))}
           for m, per in acc.items()}
    return out, const


def verdict(lo: float, hi: float) -> str:
    if hi < 0:
        return "IMPROVES on additivity in magnitude (simultaneous interval wholly below 0)"
    if lo > 0:
        return "additivity BETTER (simultaneous interval wholly above 0)"
    return "inconclusive (simultaneous interval contains 0)"


def pearson(x: np.ndarray, y: np.ndarray) -> float:
    if x.std() < 1e-12 or y.std() < 1e-12:
        return float("nan")
    return float(np.corrcoef(x, y)[0, 1])


def main() -> None:
    args = parse_args()
    seeds = [int(x) for x in args.seeds.split(",")]
    arms, const = {}, {}
    for label, (pattern, kind) in {**PRIMARY_ARMS, **EXPLORATORY_ARMS}.items():
        arms[label], c = load_arm(pattern, kind, seeds, args.output_root)
        const.update(c)
    all_pairs = sorted(const)
    out: dict = {"protocol": "Round 8, frozen before scoring (see the script's docstring)", "seeds": seeds,
                 "n_boot": args.n_boot, "alpha": args.alpha, "bootstrap_seed": args.seed}

    # ---- support -------------------------------------------------------------------------- #
    support = sorted(set.intersection(*[set(arms[a][PRIMARY]) for a in PRIMARY_ARMS]))
    excluded = sorted(set(all_pairs) - set(support))
    n = len(support)
    evaluable = n >= MIN_PAIRS
    logger.info("pairs scored: %d (expected %d); primary support: %d; excluded: %s",
                len(all_pairs), N_PAIRS_EXPECTED, n, excluded or "none")
    out.update({"pairs": support, "excluded_pairs": excluded, "primary_evaluable": evaluable})
    idx = resample_indices(n, args.n_boot, args.seed)

    def vec(arm: str, m: str, pairs: list[str] = support) -> np.ndarray:
        return np.array([arms[arm][m].get(p, np.nan) for p in pairs])

    # ---- primary ------------------------------------------------------------------------- #
    E = {a: vec(a, PRIMARY) for a in arms}
    fam = maxt_family({f"{a}-{b}": E[a] - E[b] for a, b in CONTRASTS}, idx, args.alpha)
    logger.info("\n%s\nPRIMARY: mean e_p = ‖Δ̂ − Δ‖/‖Δ‖ on each pair's top-20 genes (lower better)\n%s",
                "=" * 96, "=" * 96)
    for a in PRIMARY_ARMS:
        pi = percentile_interval(E[a], idx, args.alpha)
        logger.info("%-16s mean e %.3f  [%.3f, %.3f]", a, pi["mean"], *pi["ci"])
    logger.info("max-t critical value over %d contrasts: %.3f", len(CONTRASTS), fam["critical_value"])
    out["primary"] = {"arm_means": {a: float(E[a].mean()) for a in PRIMARY_ARMS},
                      "critical_value": fam["critical_value"], "contrasts": {}}
    for a, b in CONTRASTS:
        k = f"{a}-{b}"
        c = fam["contrasts"][k]
        lo, hi = c["ci_simultaneous"]
        d = E[a] - E[b]
        below = float(np.mean(d < 0))
        lr = vec(a, "log_r")
        geo = float(np.exp(np.nanmean(lr)))
        v = verdict(lo, hi) if evaluable else "not evaluable under the protocol (fewer than 18 pairs)"
        logger.info("%-26s %+.3f  simultaneous [%+.3f, %+.3f]  pairs below additivity %d/%d  "
                    "geo-mean error ratio %.2f", k, c["diff"], lo, hi, int((d < 0).sum()), n, geo)
        logger.info("    -> %s", v)
        out["primary"]["contrasts"][k] = {**c, "fraction_pairs_below_reference": below,
                                          "geometric_mean_error_ratio": geo, "verdict": v}

    # ---- noise floor ------------------------------------------------------------------------ #
    fe = np.array([const[p]["floor_e"] for p in support])
    fea = np.array([const[p]["floor_e_all"] for p in support])
    logger.info("\nnoise floor (error a perfect predictor would show): mean f_p %.3f on top-20 genes, %.3f on all genes",
                fe.mean(), fea.mean())
    out["noise_floor"] = {"mean_floor_e": float(fe.mean()), "mean_floor_e_all": float(fea.mean())}

    # ---- secondaries ------------------------------------------------------------------------ #
    logger.info("\n%s\nSECONDARY (percentile intervals, no verdicts)\n%s", "=" * 96, "=" * 96)
    lam = np.array([const[p]["lam"] for p in support])
    learned = [a for a in arms if a not in (REFERENCE, "average")]
    out["secondary"] = {}

    def report(metric: str, arm_list: list[str], ref: str | None, label: str) -> None:
        res = {}
        for a in arm_list:
            x = vec(a, metric)
            ok = np.isfinite(x)
            if ref is not None:
                x = x - vec(ref, metric)
                ok &= np.isfinite(x)
            if ok.sum() < 5:
                logger.info("  %-16s too few pairs (%d)", a, int(ok.sum()))
                continue
            ix = idx if ok.all() else resample_indices(int(ok.sum()), args.n_boot, args.seed)
            pi = percentile_interval(x[ok], ix, args.alpha)
            res[a] = {**pi, "n_pairs": int(ok.sum())}
            logger.info("  %-16s %+.3f  [%+.3f, %+.3f]  (%d pairs)", a, pi["mean"], *pi["ci"], int(ok.sum()))
        out["secondary"][label] = res

    logger.info("\n1. interaction recovery, measured singles (higher better)")
    report("interaction_r", learned, None, "interaction_r")
    logger.info("   diagnostic: with the model's own predicted singles")
    report("internal_r", learned, None, "internal_r")

    logger.info("\n2. scale: mean |s_p − λ_p| (lower better; additivity's is |1 − λ_p|, mean %.3f)",
                float(np.mean(np.abs(1 - lam))))
    report("scale_abs_err", [REFERENCE] + learned, None, "scale_abs_err")
    logger.info("   difference from additivity")
    report("scale_abs_err", learned, REFERENCE, "scale_abs_err_minus_additive")
    logger.info("   correlation across pairs of seed-averaged s_p with λ_p (does it know which pairs are super-additive?)")
    out["secondary"]["scale_lambda_correlation"] = {}
    for a in learned:
        s = vec(a, "scale")
        ok = np.isfinite(s) & np.isfinite(lam)
        r = pearson(s[ok], lam[ok])
        ix = resample_indices(int(ok.sum()), args.n_boot, args.seed)
        boot = np.array([pearson(s[ok][i], lam[ok][i]) for i in ix])
        lo, hi = np.nanpercentile(boot, [100 * args.alpha / 2, 100 * (1 - args.alpha / 2)])
        logger.info("  %-16s r %+.3f  [%+.3f, %+.3f]  mean s %.3f vs mean λ %.3f",
                    a, r, lo, hi, float(np.nanmean(s)), float(lam.mean()))
        out["secondary"]["scale_lambda_correlation"][a] = {"r": r, "ci": [float(lo), float(hi)],
                                                           "mean_scale": float(np.nanmean(s))}

    logger.info("\n3. e_p over all measured genes (lower better), arm means")
    report("rel_err_all", list(arms), None, "rel_err_all")
    logger.info("   difference from additivity")
    report("rel_err_all", [a for a in arms if a != REFERENCE], REFERENCE, "rel_err_all_minus_additive")

    logger.info("\n4. Δ-correlation (higher better), arm means")
    report("delta_r", list(arms), None, "delta_r")

    # ---- exploratory arms ------------------------------------------------------------------- #
    logger.info("\n%s\nEXPLORATORY ARMS on the primary endpoint (no verdict)\n%s", "=" * 96, "=" * 96)
    out["exploratory"] = {}
    for a in EXPLORATORY_ARMS:
        x = E[a] - E[REFERENCE]
        ok = np.isfinite(x)
        ix = idx if ok.all() else resample_indices(int(ok.sum()), args.n_boot, args.seed)
        pi = percentile_interval(x[ok], ix, args.alpha)
        logger.info("%-16s mean e %.3f   minus additive %+.3f  [%+.3f, %+.3f]   pairs below additivity %d/%d",
                    a, float(np.nanmean(E[a])), pi["mean"], *pi["ci"], int((x[ok] < 0).sum()), int(ok.sum()))
        out["exploratory"][a] = {"mean_e": float(np.nanmean(E[a])), "minus_additive": pi,
                                 "fraction_below_reference": float(np.mean(x[ok] < 0))}

    # ---- stratification --------------------------------------------------------------------- #
    strong = sorted(support, key=lambda p: const[p]["rel_gi"], reverse=True)[:N_STRONG]
    ix = resample_indices(len(strong), args.n_boot, args.seed)
    logger.info("\nDESCRIPTIVE: the %d most strongly interacting pairs (largest rel_GI)", len(strong))
    out["strong_interaction"] = {"pairs": strong, "arms": {}}
    for a in arms:
        x = vec(a, PRIMARY, strong)
        d = x - vec(REFERENCE, PRIMARY, strong)
        ok = np.isfinite(d)
        pi = percentile_interval(d[ok], ix if ok.all() else resample_indices(int(ok.sum()), args.n_boot, args.seed))
        logger.info("  %-16s mean e %.3f   minus additive %+.3f  [%+.3f, %+.3f]", a, float(np.nanmean(x)), pi["mean"], *pi["ci"])
        out["strong_interaction"]["arms"][a] = {"mean_e": float(np.nanmean(x)), "minus_additive": pi}

    # ---- per pair ---------------------------------------------------------------------------- #
    logger.info("\nPER PAIR (seed-averaged e_p; additive = rel_GI; floor = split-half f_p; λ = Round 4's scale)")
    logger.info("%-20s %6s %6s %6s " + " ".join(["%14s"] * len(arms)), "pair", "λ", "floor", "", *arms)
    out["per_pair"] = {}
    for p in sorted(support, key=lambda q: const[q]["rel_gi"], reverse=True):
        row = [arms[a][PRIMARY].get(p, float("nan")) for a in arms]
        logger.info("%-20s %6.3f %6.3f %6s " + " ".join(["%14.3f"] * len(arms)),
                    p, const[p]["lam"], const[p]["floor_e"], "", *row)
        out["per_pair"][p] = {"lam": const[p]["lam"], "floor_e": const[p]["floor_e"], "rel_gi": const[p]["rel_gi"],
                              "rel_err": dict(zip(arms, row)),
                              "scale": {a: arms[a]["scale"].get(p, float("nan")) for a in arms}}

    logger.info("\nNOTE: seeds are averaged per pair before the bootstrap, so intervals reflect the finite set")
    logger.info("      of %d pairs, not training-seed variation; pairs share genes, so they are not i.i.d.", n)
    if args.out:
        Path(args.out).write_text(json.dumps(out, indent=2))
        logger.info("\nwrote %s", args.out)


if __name__ == "__main__":
    main()
