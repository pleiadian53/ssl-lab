"""The composition ablation: does a DeepSets gene-set embedding beat the additive sum?

Every learned model in this project embeds a combination as the sum of its genes' learned
vectors, ``z_p(A+B) = e(A) + e(B)`` (``GeneSetEmbedding``, ``compose="additive"``). The
DeepSets composition, ``z_p = phi(psi(e(A)) + psi(e(B)))``, is nonlinear, so a pair's
embedding no longer has to be the sum of its singles'. This ablation asks whether that
freedom helps a model predict held-out pairs, in the two strongest learned model families.
It is a separate ablation, not Round 8: it shares Round 8's metric definitions and
scoring code (:mod:`ssllab.eval.interaction`, 19) but does not change Round 8's endpoint.

PROTOCOL (fixed in writing before any DeepSets run was scored)
==============================================================

Arms, three training seeds each, all trained on the combo split with the frozen Stage A
encoder; flows graded through the canonical count decoder
(``output/norman_flow_control/checkpoints/count_decoder.pt``):

    flow_add   transport flow, additive          norman_sweep_control_s{0,1,2}
    flow_ds    transport flow, DeepSets           norman_sweep_control_ds_s{0,1,2}
    vae_add    conditioned NB-VAE, additive       norman_vae_cond_s{0,1,2}
    vae_ds     conditioned NB-VAE, DeepSets       norman_vae_cond_ds_s{0,1,2}

The DeepSets runs differ from their additive twins only in ``--compose deepsets``.

Predictions. Each run's mean profiles are generated by 19 exactly as 06 (flows) and 09
(NB-VAE) generate them: 200 cells per pair, generation seed 0, 100 Euler steps and
guidance 1 for flows. 19 stops unless its Δ-correlation reproduces the run's stored
report to 1e-9. Model-internal singles use a separate generator seeded 1.

Pairs. The 20 held-out combinations the standing benchmark scores (at least 20 held-out
cells, present in the DE table). Genes: each pair's top-20 DE genes by Wilcoxon |z|, the
set Δ-correlation uses. Space: log1p-CP10K. Control mean over all control cells.
Singles: each gene's measured effect from its training cells.

Primary endpoint. Per pair p and seed, ``log r_p = log ‖Δ̂_p − Δ_p‖ − log ‖I_p‖`` on the
pair's top-20 genes, with ``I_p = Δ_p − Δ_A − Δ_B`` the measured interaction. Lower is
better; 0 is the additive reference.

Primary family: two contrasts, simultaneous over the family.

    flow_ds - flow_add      vae_ds - vae_add

Each contrast is the mean over pairs of the per-pair difference in seed-averaged
``log r_p``. Joint paired bootstrap over pairs, 10,000 resamples, seed 0, one resample
shared by both contrasts; max-t simultaneous 95% intervals (``ssllab.eval.bootstrap``,
the procedure of 12).

Decision rule, per family. DeepSets improves on its additive predecessor if the
simultaneous interval lies wholly below 0; it is worse if wholly above 0; otherwise the
result is inconclusive. Reported with each contrast: the geometric-mean error ratio
``exp(diff)`` with its interval, and the fraction of pairs where DeepSets has the lower
error. If neither family improves, the additive composition stays the default.

Two different questions, kept apart. (1) Does DeepSets improve on the learned additive
predecessor? The primary family above, the only verdict this ablation makes. (2) Does
any arm beat the empirical additive reference? Each arm's mean ``log r_p`` against 0,
with its geometric-mean ratio and the fraction of pairs with ``r_p < 1``: descriptive
only, plain intervals, no verdict, because that is Round 8's question.

Zero and near-zero handling (``ssllab.eval.interaction``). An error norm below 1e-12 is
raised to 1e-12 before the log. If ``‖I_p‖ ≤ 1e-6 · ‖Δ_p‖`` the pair's interaction is
numerically zero and its ratios are NaN. Correlations are NaN when either vector is
constant (standard deviation below 1e-12).

Aggregation order. Per pair and seed compute the metric; average over seeds per pair
(the arithmetic mean, so for ``log r_p`` the log of the geometric mean over seeds); then
average over pairs. Geometric-mean ratios are exp of the mean log. ``e_p`` and the
correlations are averaged arithmetically.

Missing values. A pair enters a metric for an arm only if every seed gives a finite
value; a pair enters a contrast or a comparison only if every arm involved has it. Every
excluded pair is listed. The primary verdict stands only if at least 18 of the 20 pairs
remain; otherwise the primary is reported as not evaluable under this protocol.

Reported beside the primary, intervals only, no verdict: per-pair results (``rel_gi``,
split-half floor, each arm's ``log r_p`` and ``e_p``); Round 8's relative error ``e_p``;
interaction correlation; the model-internal interaction (correlation and log ratio,
with the model's own singles); Δ-correlation; the primary contrasts on the more strongly
interacting half of the pairs (the 10 highest ``rel_gi``).

Usage
-----
    python examples/perturbation_response/20_compare_composition.py \
        --out output/composition_ablation_compare.json
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path

import numpy as np

_SRC = Path(__file__).resolve().parents[2] / "src"
if str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

from ssllab.eval.bootstrap import maxt_family, percentile_interval, resample_indices

logging.basicConfig(level=logging.INFO, format="%(message)s")
logger = logging.getLogger(__name__)

ARMS = {
    "flow_add": ("norman_sweep_control_s{s}", "flow"),
    "flow_ds": ("norman_sweep_control_ds_s{s}", "flow"),
    "vae_add": ("norman_vae_cond_s{s}", "vae"),
    "vae_ds": ("norman_vae_cond_ds_s{s}", "vae"),
}
CONTRASTS = [("flow_ds", "flow_add"), ("vae_ds", "vae_add")]
PRIMARY = "log_r"
SECONDARY = ["rel_err", "interaction_r", "internal_r", "internal_log_r", "delta_r"]
LOWER_IS_BETTER = {"log_r", "rel_err", "internal_log_r"}
MIN_PAIRS = 18
N_PAIRS_EXPECTED = 20


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="The composition ablation: DeepSets vs additive gene-set embedding.")
    p.add_argument("--output-root", default="output")
    p.add_argument("--seeds", default="0,1,2")
    p.add_argument("--n-boot", type=int, default=10000)
    p.add_argument("--alpha", type=float, default=0.05)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", default=None)
    return p.parse_args()


def load_arm(pattern: str, kind: str, seeds: list[int], root: str) -> tuple[dict, dict]:
    """Seed-average every metric per pair. Returns ({metric: {pair: value}}, {pair: per-pair constants})."""
    acc: dict[str, dict[str, list[float]]] = {}
    const: dict[str, dict] = {}
    for s in seeds:
        path = Path(root) / pattern.format(s=s) / "reports" / f"interaction_{kind}.json"
        if not path.exists():
            raise SystemExit(f"missing {path}; run 19_score_interaction.py first")
        for pair, d in json.loads(path.read_text())["per_pert"].items():
            for m in [PRIMARY] + SECONDARY:
                acc.setdefault(m, {}).setdefault(pair, []).append(float(d[m]))
            const[pair] = {"rel_gi": d["rel_gi"], "floor_log_r": d["floor_log_r"]}
    out = {}
    for m, per in acc.items():
        out[m] = {p: float(np.mean(v)) for p, v in per.items()
                  if len(v) == len(seeds) and all(np.isfinite(v))}
    return out, const


def verdict(lo: float, hi: float) -> str:
    if hi < 0:
        return "DeepSets LOWER error (simultaneous interval wholly below 0)"
    if lo > 0:
        return "DeepSets HIGHER error (simultaneous interval wholly above 0)"
    return "inconclusive (simultaneous interval contains 0)"


def main() -> None:
    args = parse_args()
    seeds = [int(x) for x in args.seeds.split(",")]
    arms, const = {}, {}
    for label, (pattern, kind) in ARMS.items():
        arms[label], c = load_arm(pattern, kind, seeds, args.output_root)
        const.update(c)

    all_pairs = sorted(const)
    out: dict = {"protocol": "composition ablation, frozen before scoring", "seeds": seeds,
                 "n_boot": args.n_boot, "alpha": args.alpha, "bootstrap_seed": args.seed}

    # ---- support for the primary -------------------------------------------------------- #
    support = sorted(set.intersection(*[set(arms[a][PRIMARY]) for a in arms]))
    excluded = sorted(set(all_pairs) - set(support))
    n = len(support)
    evaluable = n >= MIN_PAIRS
    logger.info("pairs scored: %d (expected %d); primary support: %d; excluded: %s",
                len(all_pairs), N_PAIRS_EXPECTED, n, excluded or "none")
    out.update({"pairs": support, "excluded_pairs": excluded, "primary_evaluable": evaluable})
    idx = resample_indices(n, args.n_boot, args.seed)
    V = {a: np.array([arms[a][PRIMARY][p] for p in support]) for a in arms}

    # ---- (1) the primary family: DeepSets vs its additive predecessor -------------------- #
    fam = maxt_family({f"{a}-{b}": V[a] - V[b] for a, b in CONTRASTS}, idx, args.alpha)
    logger.info("\n%s", "=" * 96)
    logger.info("(1) PRIMARY: does DeepSets improve on its learned additive predecessor?  metric: mean log r_p")
    logger.info("%s", "=" * 96)
    logger.info("max-t critical value over %d contrasts: %.3f", len(CONTRASTS), fam["critical_value"])
    logger.info("%-20s %8s  %-20s %-20s %-22s %s", "contrast", "diff", "simultaneous 95%",
                "geo-mean ratio", "ratio interval", "pairs improved")
    out["primary"] = {"critical_value": fam["critical_value"], "contrasts": {}}
    for a, b in CONTRASTS:
        k = f"{a}-{b}"
        c = fam["contrasts"][k]
        lo, hi = c["ci_simultaneous"]
        d = V[a] - V[b]
        improved = float(np.mean(d < 0))
        logger.info("%-20s %+8.3f  [%+.3f, %+.3f]     %-20.3f [%.3f, %.3f]       %d/%d (%.0f%%)",
                    k, c["diff"], lo, hi, np.exp(c["diff"]), np.exp(lo), np.exp(hi),
                    int((d < 0).sum()), n, 100 * improved)
        v = verdict(lo, hi) if evaluable else "not evaluable under the protocol (fewer than 18 pairs)"
        logger.info("    -> %s", v)
        out["primary"]["contrasts"][k] = {**c, "geometric_mean_ratio": float(np.exp(c["diff"])),
                                          "ratio_ci_simultaneous": [float(np.exp(lo)), float(np.exp(hi))],
                                          "fraction_pairs_improved": improved, "verdict": v}

    # ---- (2) descriptive: each arm against the empirical additive reference ------------- #
    logger.info("\n%s", "=" * 96)
    logger.info("(2) DESCRIPTIVE ONLY: each arm against the additive reference (log r = 0). Round 8's question; no verdict.")
    logger.info("%s", "=" * 96)
    logger.info("%-10s %10s  %-20s %14s  %-18s %s", "arm", "mean log r", "95% interval", "geo-mean r",
                "r interval", "pairs with r < 1")
    out["vs_additive_reference"] = {}
    for a in arms:
        pi = percentile_interval(V[a], idx, args.alpha)
        frac = float(np.mean(V[a] < 0))
        logger.info("%-10s %+10.3f  [%+.3f, %+.3f]     %10.3f      [%.3f, %.3f]      %d/%d",
                    a, pi["mean"], *pi["ci"], np.exp(pi["mean"]), *np.exp(pi["ci"]), int((V[a] < 0).sum()), n)
        out["vs_additive_reference"][a] = {**pi, "geometric_mean_r": float(np.exp(pi["mean"])),
                                           "r_ci": [float(x) for x in np.exp(pi["ci"])], "fraction_r_below_1": frac}
    floors = np.array([const[p]["floor_log_r"] for p in support])
    logger.info("split-half noise floor (mean log r a perfect predictor would show): %+.3f  (geo-mean r %.3f)",
                floors.mean(), np.exp(floors.mean()))
    out["noise_floor_mean_log_r"] = float(floors.mean())

    # ---- secondaries: intervals only ------------------------------------------------------ #
    logger.info("\n%s", "=" * 96)
    logger.info("SECONDARY (unadjusted intervals, no verdicts)")
    logger.info("%s", "=" * 96)
    out["secondary"] = {}
    for m in SECONDARY:
        sup = sorted(set.intersection(*[set(arms[a][m]) for a in arms]))
        if len(sup) < 5:
            logger.info("%-15s too few pairs (%d)", m, len(sup))
            continue
        ix = resample_indices(len(sup), args.n_boot, args.seed)
        W = {a: np.array([arms[a][m][p] for p in sup]) for a in arms}
        arrow = "lower better" if m in LOWER_IS_BETTER else "higher better"
        logger.info("\n%s (%s; %d pairs)  arm means: %s", m, arrow, len(sup),
                    "  ".join(f"{a}={W[a].mean():.3f}" for a in arms))
        out["secondary"][m] = {"n_pairs": len(sup), "arm_means": {a: float(W[a].mean()) for a in arms}, "contrasts": {}}
        for a, b in CONTRASTS:
            pi = percentile_interval(W[a] - W[b], ix, args.alpha)
            logger.info("    %-20s %+8.3f  [%+.3f, %+.3f]", f"{a}-{b}", pi["mean"], *pi["ci"])
            out["secondary"][m]["contrasts"][f"{a}-{b}"] = pi

    strong = sorted(support, key=lambda p: const[p]["rel_gi"], reverse=True)[: n // 2]
    ix = resample_indices(len(strong), args.n_boot, args.seed)
    S = {a: np.array([arms[a][PRIMARY][p] for p in strong]) for a in arms}
    logger.info("\nprimary on the more strongly interacting half (%d pairs, highest rel_gi):", len(strong))
    out["strong_half"] = {"pairs": strong, "contrasts": {}}
    for a, b in CONTRASTS:
        pi = percentile_interval(S[a] - S[b], ix, args.alpha)
        logger.info("    %-20s %+8.3f  [%+.3f, %+.3f]", f"{a}-{b}", pi["mean"], *pi["ci"])
        out["strong_half"]["contrasts"][f"{a}-{b}"] = pi

    # ---- per-pair table --------------------------------------------------------------------- #
    logger.info("\nPER PAIR (seed-averaged; log r < 0 beats additivity; e = Round 8 relative error)")
    head = "%-20s %7s %8s " + " ".join(["%9s"] * len(arms)) + "   " + " ".join(["%8s"] * len(arms))
    logger.info(head, "pair", "rel_gi", "floor", *[f"lr:{a}" for a in arms], *[f"e:{a}" for a in arms])
    out["per_pair"] = {}
    for p in sorted(support, key=lambda q: const[q]["rel_gi"], reverse=True):
        lr = [arms[a][PRIMARY][p] for a in arms]
        e = [arms[a]["rel_err"].get(p, float("nan")) for a in arms]
        logger.info("%-20s %7.3f %+8.3f " + " ".join(["%+9.3f"] * len(arms)) + "   " + " ".join(["%8.3f"] * len(arms)),
                    p, const[p]["rel_gi"], const[p]["floor_log_r"], *lr, *e)
        out["per_pair"][p] = {"rel_gi": const[p]["rel_gi"], "floor_log_r": const[p]["floor_log_r"],
                              "log_r": dict(zip(arms, lr)), "rel_err": dict(zip(arms, e))}

    logger.info("\nNOTE: seeds are averaged per pair before the bootstrap, so intervals reflect the finite set")
    logger.info("      of %d pairs, not training-seed variation; pairs share genes, so they are not i.i.d.", n)
    if args.out:
        Path(args.out).write_text(json.dumps(out, indent=2))
        logger.info("\nwrote %s", args.out)


if __name__ == "__main__":
    main()
